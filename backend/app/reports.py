"""Downloadable Markdown reports for audits and verdicts (every flag keeps its evidence links)."""
from __future__ import annotations

from backend.common.schemas import AuditReport, DocumentInfo, Verdict

STATUS = {"verified": "✅ Verified", "metadata_mismatch": "⚠️ Metadata mismatch", "not_found": "❌ Not found",
          "could_not_verify": "❔ Could not verify"}
RETRACTION = {"retracted": "❌ Retracted", "corrected": "⚠️ Corrected", "expression_of_concern": "⚠️ Expression of concern",
              "none_found": "No notices", "could_not_verify": "❔ Could not verify", "not_checked": "Not covered"}
DECISION = {"submit": "✅ SUBMIT", "revise": "⚠️ REVISE", "dont_submit": "❌ DON'T SUBMIT"}


def _cell(s: str | None) -> str:
    return (s or "").replace("|", "\\|").replace("\n", " ")


def audit_markdown(r: AuditReport, doc: DocumentInfo | None) -> str:
    title = (doc.title or doc.filename) if doc else r.document_id
    s = r.summary
    out = [f"# Cite and Slayy · CiteGuard report", "", f"**Paper:** {title}  ", f"**Audit:** `{r.audit_id}` · {r.created_at:%Y-%m-%d %H:%M} UTC  ",
           f"**Integrity score:** **{r.score:.0f}/100**{' (low confidence)' if r.low_confidence else ''}", ""]
    if r.self_status and r.self_status.retraction == "retracted":
        out += [f"> ❌ **This paper itself has been retracted.** Notice(s): " +
                ", ".join(f"[{d}](https://doi.org/{d})" for d in r.self_status.notices), ""]
    out += ["## Summary", "",
            f"- References: {s.get('verified', 0)}/{s.get('references', 0)} verified · {s.get('metadata_mismatch', 0)} mismatch · "
            f"{s.get('not_found', 0)} not found · {s.get('could_not_verify', 0)} could not verify",
            f"- Retracted citations: {s.get('retracted_cited', 0)} · corrected / EoC: {s.get('corrected_cited', 0)}",
            f"- Claims: {s.get('supported', 0)} supported · {s.get('unclear', 0)} unclear · {s.get('unsupported', 0)} unsupported "
            f"(of {s.get('claims', 0)} checked)",
            f"- Tortured phrases: {s.get('phrases', 0)} · possible-overlap paragraphs: {s.get('overlaps', 0)}", ""]
    for w in r.warnings:
        out.append(f"> ⚠️ {w}")
    out += ["", "## Score breakdown", "", "| Term | Value | Formula | Inputs |", "|---|---|---|---|"]
    for t in r.score_terms:
        val = f"{t.value:.1f} / {t.max:g}" if t.max else f"{t.value:.1f}"
        out.append(f"| {t.name} | {val} | `{t.formula}` | {', '.join(f'{k} {v:g}' for k, v in t.inputs.items())} |")
    out += ["", "## References", "", "| Ref | Existence | Retraction | Matched record | Evidence |", "|---|---|---|---|---|"]
    for ref in r.references:
        rec = ref.matched
        rec_s = f"[{_cell(rec.title)}]({rec.url or ('https://doi.org/' + rec.doi if rec.doi else '')}) ({rec.year})" if rec else _cell(ref.parsed.raw[:120])
        if ref.mismatches:
            rec_s += " · " + "; ".join(f"{d.field}: paper “{_cell(d.in_paper)}” vs record “{_cell(d.in_record)}”" for d in ref.mismatches)
        notices = " ".join(f"[{d}](https://doi.org/{d})" for d in ref.retraction_notices)
        ev = " ".join(f"[{e.source}]({e.request_url})" for e in ref.evidence if e.request_url)[:600]
        out.append(f"| {ref.label} | {STATUS[ref.status]} | {RETRACTION[ref.retraction]} {notices} | {rec_s} | {ev} |")
    flagged = [c for c in r.claims if c.label in ("unsupported", "unclear") and c.cited_abstract]
    if flagged:
        out += ["", "## Claims to review", ""]
        for c in flagged:
            out += [f"- **{c.label.title()}** (p.{c.page + 1}, ref {c.ref_index}, similarity {c.similarity or 0:.2f}): “{c.sentence}”  ",
                    f"  _Cited:_ {c.cited_title} · _Why:_ {c.rationale}"]
    if r.phrases:
        out += ["", "## Tortured phrases", ""]
        out += [f"- p.{h.page + 1}: “{h.phrase}” → expected “{h.expected}” ([source]({h.source_url}))" for h in r.phrases]
    if r.overlaps:
        out += ["", "## Possible overlap (pointers for a human, not a plagiarism finding)", ""]
        out += [f"- p.{o.page + 1}: similarity {o.similarity:.2f} with “{o.matched.title}” ({o.relation})" for o in r.overlaps]
    out += ["", "---", "Generated by Cite and Slayy. Data: Crossref (incl. Retraction Watch), Semantic Scholar, OpenAlex, arXiv."]
    return "\n".join(out)


def verdict_markdown(v: Verdict, doc: DocumentInfo | None) -> str:
    title = (doc.title or doc.filename) if doc else v.document_id
    out = [f"# Cite and Slayy · Go / No-Go verdict", "", f"**Paper:** {title}  ", f"**Verdict:** **{DECISION[v.decision]}**  ",
           f"**Jury (weighted):** {v.weighted_mean if v.weighted_mean is not None else '—'}/10 · **Integrity:** "
           f"{f'{v.integrity:.0f}' if v.integrity is not None else '—'}/100  ",
           f"**Reviewers:** {'Azora reviewer panel' if v.llm.get('available', True) else 'rule-based checklist only'}"
           + (f" (read a condensed {v.llm.get('chars_read')}/{v.llm.get('chars_total')} characters)" if v.llm.get("condensed") else ""), "",
           "## Why", ""]
    out += [f"- {r}" for r in v.triggered_rules]
    out += ["", "## Ranked fixes", ""]
    out += [f"{f.rank}. {'**[BLOCKING]** ' if f.blocking else ''}{f.fix} _({f.source})_" for f in v.ranked_fixes]
    out += ["", "## Reviewers", ""]
    for p in v.personas:
        if p.error:
            out.append(f"### {p.persona}: not assessed\n{p.error}\n")
            continue
        out += [f"### {p.persona}: {p.score}/10 (confidence {p.confidence or 0:.0%})", p.summary, "", "**Weaknesses**"]
        out += [f"- {w}" for w in p.weaknesses] + ["", "**Fixes**"] + [f"- {x}" for x in p.fixes] + [""]
    if v.checklist:
        out += ["## Readiness checklist", ""] + [f"- {'✅' if c.passed else '❌'} {c.name}: {c.detail}" for c in v.checklist]
    if v.venue_suggestions:
        out += ["", "## Where similar work was published (OpenAlex)", ""]
        out += [f"- {s.venue} ({s.count} similar)" for s in v.venue_suggestions]
    out += ["", "## Decision rules", ""] + [f"{i}. {r}" for i, r in enumerate(v.rules, 1)]
    out += ["", "---", "Generated by Cite and Slayy."]
    return "\n".join(out)
